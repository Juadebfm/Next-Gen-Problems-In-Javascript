// Traffic light system
// if else statements

let light = "yellow";

if (light === "red") {
  console.log("Stop");
} else if (light === "yellow") {
  console.log("Slow Down, Get Ready");
} else if (light === "green") {
  console.log("Go");
} else {
  console.log("there is an issue with the light");
}

let lightSwitch = "dhdhdhdh";

switch (lightSwitch) {
  case "red":
    console.log("Stop");
    break;
  case "yellow":
    console.log("Slow Down, Get Ready");
    break;
  case "green":
    console.log("Go");
    break;
  default:
    console.log("there is an issue with the light");
}
